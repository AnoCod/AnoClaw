const dictionaries: Record<PluginLocale, Record<PluginTranslationKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

declare global {
  interface Window {
    __ANOCLAW_LOCALE__?: unknown;
  }
}

let currentLocale: PluginLocale = normalizePluginLocale(
  typeof window === 'undefined' ? undefined : window.__ANOCLAW_LOCALE__,
);

export function normalizePluginLocale(value: unknown): PluginLocale {
  const raw = String(value || '').trim().toLowerCase();
  return raw === 'en' || raw === 'en-us' ? 'en-US' : 'zh-CN';
}

export function setPluginLocale(value: unknown): PluginLocale {
  currentLocale = normalizePluginLocale(value);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLocale;
  }
  return currentLocale;
}

export function getPluginLocale(): PluginLocale {
  return currentLocale;
}

export function t(key: PluginTranslationKey, params: TranslationParams = {}): string {
  const template = dictionaries[currentLocale][key] || dictionaries['en-US'][key] || key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? '' : String(value);
  });
}

export function dateLocale(): string {
  return currentLocale;
}

export const pluginDictionaries = {
  'zh-CN': zhCN,
  'en-US': enUS,
} as const;
